def _format_chunks(chunks: list[RetrievedChunk]) -> str:
    if not chunks:
        return "(выдержки нормативных актов не найдены)"
    parts: list[str] = []
    for chunk in chunks:
        text = (chunk.text or "").strip()
        section = (chunk.section_number or "").strip()
        is_table = section.lower().startswith("табл.")
        limit = 1100 if is_table else 550
        if len(text) > limit:
            text = text[:limit].rstrip() + "…"
        try:
            region = get_region(chunk.region_code)
            npa_short = short_npa_cite(region.document_title)
            region_label = region.display_name
        except Exception:  # noqa: BLE001
            npa_short = "НПА"
            region_label = chunk.region_code or "—"
        label = "пункт"
        parts.append(
            f"[регион={region_label}] [НПА={npa_short}] "
            f"[{label} {section or 'без номера'}] {text}"
        )
    return "\n\n".join(parts)


def _tier_label(object_tier: str | None) -> str:
    if (object_tier or "").strip().lower() == "group1":
        return "профильный (персональные нормы РНГП)"
    return "рамочный (коммерция / общие показатели РНГП + федеральный слой)"


def build_extraction_prompt(
    business_type: str,
    region_code: str,
    chunks: list[RetrievedChunk],
    federal_chunks: list[RetrievedChunk] | None = None,
    object_tier: str = "group2",
) -> str:
    region = get_region(region_code)
    return (
        f"Регион: {region.display_name}\n"
        f"НПА региона: {region.document_title}\n"
        f"Тип объекта капитального строительства: {business_type}\n"
        f"Класс объекта для РНГП: {_tier_label(object_tier)}\n\n"
        f"Выдержки регионального норматива:\n{_format_chunks(chunks)}\n\n"
        f"Выдержки федеральных норм ({federal_sp42_label()} и др.):\n"
        f"{_format_chunks(federal_chunks or [])}\n\n"
        f'Верни JSON вида {{"region_code": "{region_code}", "business_type": "{business_type}", '
        f'"items": [{{"category": ..., "description": ..., "citation": ..., "is_specific": true/false, '
        f'"source_level": "федеральный"/"региональный"}}]}}'
    )


